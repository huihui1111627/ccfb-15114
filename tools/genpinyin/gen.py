#!/usr/bin/env python3
"""Generate sortengine/pinyin_table.gen.go from Unicode Unihan kMandarin.

Usage:
    python3 tools/genpinyin/gen.py Unihan_Readings.txt 18.0.0 sortengine/pinyin_table.gen.go

The table maps each Han code point to syllable*5+tone, where syllables are
numbered in alphabetical order (418 of them) and tone is 1..4. Codes are small
enough for the encoder's two-byte unit. Code points outside the dense
U+3400..U+9FFF range go into sorted parallel arrays for binary search.
"""
import re
import sys

BASE = {'ā': 'a', 'á': 'a', 'ǎ': 'a', 'à': 'a', 'ē': 'e', 'é': 'e', 'ě': 'e', 'è': 'e',
        'ī': 'i', 'í': 'i', 'ǐ': 'i', 'ì': 'i', 'ō': 'o', 'ó': 'o', 'ǒ': 'o', 'ò': 'o',
        'ū': 'u', 'ú': 'u', 'ǔ': 'u', 'ù': 'u', 'ǖ': 'v', 'ǘ': 'v', 'ǚ': 'v', 'ǜ': 'v',
        'ń': 'n', 'ň': 'n', 'ǹ': 'n', 'ḿ': 'm', 'ü': 'v', '̄': '', '́': '',
        '̌': '', '̀': ''}
TONE = {'ā': 1, 'ē': 1, 'ī': 1, 'ō': 1, 'ū': 1, 'ǖ': 1,
        'á': 2, 'é': 2, 'í': 2, 'ó': 2, 'ú': 2, 'ǘ': 2, 'ń': 2, 'ḿ': 2,
        'ǎ': 3, 'ě': 3, 'ǐ': 3, 'ǒ': 3, 'ǔ': 3, 'ǚ': 3, 'ň': 3,
        'à': 4, 'è': 4, 'ì': 4, 'ò': 4, 'ù': 4, 'ǜ': 4, 'ǹ': 4}

if len(sys.argv) != 4:
    sys.exit(__doc__)

rows = []
for line in open(sys.argv[1], encoding='utf-8'):
    if '\tkMandarin\t' not in line:
        continue
    cp, _, val = line.rstrip('\n').split('\t')
    cp = int(cp[2:], 16)
    # Multi-reading entries (99 of them) take the first reading.
    v = val.split(' ')[0]
    tone = 0
    for ch in v:
        if ch in TONE:
            tone = TONE[ch]
    syl = ''.join(BASE.get(c, c) for c in v)
    if not re.fullmatch(r'[a-z]+', syl):
        raise SystemExit('bad syllable %r for U+%04X' % (syl, cp))
    rows.append((cp, syl, tone))

syls = sorted({s for _, s, _ in rows})
syl_index = {s: i for i, s in enumerate(syls)}
dense_lo, dense_hi = 0x3400, 0x9FFF
dense = [(cp, s, t) for cp, s, t in rows if dense_lo <= cp <= dense_hi]
ext = [(cp, s, t) for cp, s, t in rows if cp > dense_hi]
dense_by_cp = {cp: syl_index[s] * 5 + t for cp, s, t in dense}
dense_vals = [dense_by_cp.get(cp, 0) for cp in range(dense_lo, dense_hi + 1)]

out = []
w = out.append
w('// Code generated by tools/genpinyin; DO NOT EDIT.')
w('// Source: Unicode %s Unihan_Readings.txt kMandarin readings.' % sys.argv[2])
w('//')
w('// Ordering code: syllable*5+tone, so the first reading syllable decides')
w('// the order of a character and the tone breaks ties. Characters without a')
w('// reading fall back to their code point (see PinyinCode).')
w('')
w('package sortengine')
w('')
w('// pinyinSyllables lists every distinct toneless Mandarin syllable used by')
w('// the table, sorted in Go string (byte) order.')
w('var pinyinSyllables = [...]string{')
line = '\t'
for s in syls:
    item = '"%s", ' % s
    if len(line) + len(item) > 96:
        w(line.rstrip())
        line = '\t'
    line += item
w(line.rstrip())
w('}')
w('')
w('// pinyinDenseLo is the first code point covered by pinyinDense.')
w('const pinyinDenseLo = 0x%X' % dense_lo)
w('')
w('// pinyinDense holds syllable*5+tone for U+%04X..U+%04X; zero means no reading.'
  % (dense_lo, dense_hi))
w('var pinyinDense = [...]uint16{')
line = '\t'
for v in dense_vals:
    item = '%d, ' % v
    if len(line) + len(item) > 96:
        w(line.rstrip())
        line = '\t'
    line += item
w(line.rstrip())
w('}')
w('')
w('// pinyinExtKeys / pinyinExtVals cover supplementary code points not in the')
w('// dense range, sorted by code point for binary search.')
w('var pinyinExtKeys = [...]rune{')
line = '\t'
for cp, s, t in ext:
    item = '0x%X, ' % cp
    if len(line) + len(item) > 96:
        w(line.rstrip())
        line = '\t'
    line += item
w(line.rstrip())
w('}')
w('')
w('var pinyinExtVals = [...]uint16{')
line = '\t'
for cp, s, t in ext:
    item = '%d, ' % (syl_index[s] * 5 + t)
    if len(line) + len(item) > 96:
        w(line.rstrip())
        line = '\t'
    line += item
w(line.rstrip())
w('}')
open(sys.argv[3], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('syllables=%d dense=%d ext=%d' % (len(syls), len(dense), len(ext)), file=sys.stderr)
